void init_keyboard()
{
    register_interrupt_handler(33, handle_keyboard_interrupt);
}

static void handle_keyboard_interrupt(struct cpu_state *cpu)
{
    UNUSED(cpu);

    // The scancode is specified in 0x60 for us by the pic
    unsigned char scancode = inb(0x60);

    if (scancode == LSHIFT_SCANCODE) {
        k_flags.lshift = 0xff;
    } else if (scancode == LSHIFT_RELEASED_SCANCODE) {
        k_flags.lshift = 0x0;
    } else if (scancode == RSHIFT_SCANCODE) {
        k_flags.rshift = 0xff;
    } else if (scancode == RSHIFT_RELEASED_SCANCODE) {
        k_flags.rshift = 0x0;
    } else if (scancode == CAPS_LOCK_SCANCODE) {
        k_flags.caps = !k_flags.caps;
    }

    char chr = 0;

    if (scancode <= KEYMAP_LENGTH) {
        char upper = k_flags.lshift || k_flags.rshift || k_flags.caps;

        if (upper) {
            chr = uppercase[scancode];
        } else {
            chr = lowercase[scancode];
        }
    }

    printc(chr);

    UNUSED(chr);
}
